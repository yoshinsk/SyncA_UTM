@bp.route("/api/static-hosts", methods=["POST"])
@login_required
@csrf_protect
def add_static_host():
    payload = request.get_json(force=True, silent=True) or {}
    try:
        mac = validate_mac(payload.get("mac", ""))
        ip = validate_ipv4(payload.get("ip", ""))
    except ValidationError as e:
        return jsonify({"error": str(e)}), 400
    hostname = (payload.get("hostname") or "").strip() or ""
    lease = (payload.get("lease") or "").strip() or ""
    if lease and not LEASE_RE.match(lease):
        return jsonify({"error": "invalid lease"}), 400
    new_id = uuid.uuid4().hex
    with _store().transaction(MODULE_NAME, default_data()) as data:
        if any(h["mac"] == mac for h in data["dhcp"]["static_hosts"]):
            return jsonify({"error": f"MAC {mac} already reserved"}), 409
        data["dhcp"]["static_hosts"].append({
            "id": new_id, "mac": mac, "ip": ip, "hostname": hostname, "lease": lease,
        })
    try:
        apply_dnsmasq(current_app.config["CONFIG_DIR"])
    except RuntimeError as e:
        return jsonify({"error": str(e)}), 500
    return jsonify({"ok": True, "id": new_id}), 201


