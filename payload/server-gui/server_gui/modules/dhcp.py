@bp.route("/api/ranges", methods=["POST"])
@login_required
@csrf_protect
def add_range():
    payload = request.get_json(force=True, silent=True) or {}
    try:
        start = validate_ipv4(payload.get("start", ""))
        end = validate_ipv4(payload.get("end", ""))
    except ValidationError as e:
        return jsonify({"error": str(e)}), 400
    lease = str(payload.get("lease", "12h")).strip() or "12h"
    if not LEASE_RE.match(lease):
        return jsonify({"error": "invalid lease (e.g. 12h, 1d, 3600s, infinite)"}), 400
    interface = (payload.get("interface") or "").strip() or None
    if interface:
        try:
            interface = validate_interface(interface)
        except ValidationError as e:
            return jsonify({"error": str(e)}), 400
        candidates = _dhcp_interface_candidates()
        candidate_names = {item["name"] for item in candidates}
        if candidate_names and interface not in candidate_names:
            return jsonify({"error": f"interface is not eligible for DHCP range: {interface}"}), 400
    netmask = (payload.get("netmask") or "").strip() or None
    if netmask:
        try:
            validate_ipv4(netmask)
        except ValidationError as e:
            return jsonify({"error": str(e)}), 400

    new_id = uuid.uuid4().hex
    with _store().transaction(MODULE_NAME, default_data()) as data:
        data["dhcp"]["ranges"].append({
            "id": new_id, "interface": interface,
            "start": start, "end": end, "netmask": netmask, "lease": lease,
        })
    try:
        apply_dnsmasq(current_app.config["CONFIG_DIR"])
    except RuntimeError as e:
        return jsonify({"error": str(e)}), 500
    return jsonify({"ok": True, "id": new_id}), 201


