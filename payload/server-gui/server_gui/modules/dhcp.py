_RANGE_LEASE_RE = re.compile(r"^\d+[smhd]?$|^infinite$", re.IGNORECASE)
_MAC_RE = re.compile(r"^([0-9a-f]{2}:){5}[0-9a-f]{2}$", re.IGNORECASE)


def _parse_dhcp_range_raw(raw: str) -> dict:
    """Parse a dhcp-range value into {interface, tag, start, end, netmask, lease}.

    Handles the common shapes:
      interface:X,start,end[,netmask],lease
      set:TAG,start,end[,netmask],lease
      interface:X,set:TAG,start,end[,netmask],lease
    """
    parts = [p.strip() for p in raw.split(",") if p.strip()]
    out = {"interface": None, "tag": "", "start": None, "end": None, "netmask": None, "lease": "12h"}
    i = 0
    while i < len(parts):
        if parts[i].startswith("interface:"):
            out["interface"] = parts[i][len("interface:"):]
            i += 1
            continue
        if parts[i].startswith("set:"):
            out["tag"] = parts[i][len("set:"):]
            i += 1
            continue
        if parts[i].startswith("tag:"):
            # tag:<name> selects a range; it is not the option-scope tag set
            # by dnsmasq. Keep parsing the address portion but do not persist it
            # as the generated set:<tag> value.
            i += 1
            continue
        break
    # start
    if i >= len(parts):
        raise ValueError("start IP がありません")
    import ipaddress
    try:
        ipaddress.IPv4Address(parts[i]); out["start"] = parts[i]; i += 1
    except ValueError:
        raise ValueError(f"start IP が不正: {parts[i]!r}")
    # end
    if i >= len(parts):
        raise ValueError("end IP がありません")
    try:
        ipaddress.IPv4Address(parts[i]); out["end"] = parts[i]; i += 1
    except ValueError:
        # could be "static" or "ra-only" — unsupported
        raise ValueError(f"end IP が不正: {parts[i]!r}")
    # optional: netmask then lease, or just lease
    while i < len(parts):
        v = parts[i]
        if _RANGE_LEASE_RE.match(v):
            out["lease"] = v
        else:
            try:
                ipaddress.IPv4Address(v)
                out["netmask"] = v
            except ValueError:
                # ignore unknown field
                pass
        i += 1
    return out


def _parse_dhcp_host_raw(raw: str) -> dict:
    """Parse dhcp-host value into {mac, ip, hostname, lease}."""
    parts = [p.strip() for p in raw.split(",") if p.strip()]
    out = {"mac": None, "ip": None, "hostname": "", "lease": ""}
    import ipaddress
    for p in parts:
        if p.startswith(("set:", "tag:", "id:", "client:")):
            continue
        if _MAC_RE.match(p):
            out["mac"] = p.lower()
            continue
        try:
            ipaddress.IPv4Address(p)
            out["ip"] = p
            continue
        except ValueError:
            pass
        if _RANGE_LEASE_RE.match(p):
            out["lease"] = p
            continue
        # treat as hostname
        if not out["hostname"]:
            out["hostname"] = p
    if not out["mac"] or not out["ip"]:
        raise ValueError("dhcp-host parsing requires both MAC and IP")
    return out


def _parse_dhcp_option_raw(raw: str) -> dict:
    """Parse dhcp-option value into {tag, option, value}.

    Forms:
      OPTION,VALUE
      option:NAME,VALUE
      tag:TAG,OPTION,VALUE
      tag:TAG,option:NAME,VALUE
    """
    parts = [p.strip() for p in raw.split(",")]
    out = {"tag": "", "option": None, "value": None}
    if not parts:
        raise ValueError("empty dhcp-option")
    if parts[0].startswith("tag:"):
        out["tag"] = parts[0][len("tag:"):]
        parts = parts[1:]
    if not parts:
        raise ValueError("dhcp-option needs option + value")
    if parts[0].startswith("option:"):
        out["option"] = parts[0][len("option:"):]
        parts = parts[1:]
    elif parts[0].isdigit() or re.match(r"^[a-zA-Z][a-zA-Z0-9_\-]*$", parts[0]):
        out["option"] = parts[0]
        parts = parts[1:]
    else:
        raise ValueError(f"unrecognized option: {parts[0]!r}")
    if not parts:
        raise ValueError("dhcp-option needs value")
    out["value"] = ",".join(parts)
    return out


@bp.route("/api/import", methods=["POST"])
@login_required
@csrf_protect
def import_existing():
    """Import a single existing entry into the managed store. Body:
        {kind: "range"|"host"|"option", raw: "<the value after dhcp-X=>"}
    Returns the new id on success.
    """
    payload = request.get_json(force=True, silent=True) or {}
    kind = payload.get("kind")
    raw = (payload.get("raw") or "").strip()
    if kind not in ("range", "host", "option") or not raw:
        return jsonify({"error": "kind ('range'|'host'|'option') and raw required"}), 400
    new_id = uuid.uuid4().hex
    try:
        if kind == "range":
            parsed = _parse_dhcp_range_raw(raw)
            with _store().transaction(MODULE_NAME, default_data()) as data:
                data["dhcp"]["ranges"].append({"id": new_id, **parsed})
        elif kind == "host":
            parsed = _parse_dhcp_host_raw(raw)
            with _store().transaction(MODULE_NAME, default_data()) as data:
                if any(h["mac"] == parsed["mac"] for h in data["dhcp"]["static_hosts"]):
                    return jsonify({"error": f"MAC {parsed['mac']} already managed"}), 409
                data["dhcp"]["static_hosts"].append({"id": new_id, **parsed})
        else:  # option
            parsed = _parse_dhcp_option_raw(raw)
            with _store().transaction(MODULE_NAME, default_data()) as data:
                data["dhcp"]["options"].append({"id": new_id, **parsed})
    except ValueError as e:
        return jsonify({"error": str(e)}), 400
    try:
        apply_dnsmasq(current_app.config["CONFIG_DIR"])
    except RuntimeError as e:
        # Roll back the import
        with _store().transaction(MODULE_NAME, default_data()) as data:
            for k in ("ranges", "static_hosts", "options"):
                data["dhcp"][k] = [r for r in data["dhcp"][k] if r["id"] != new_id]
        return jsonify({"error": str(e)}), 500
    return jsonify({
        "ok": True, "id": new_id, "parsed": parsed,
        "note": "管理対象に取り込みました。重複を避けるため、元ファイル側のエントリは手動でコメントアウトしてください。",
    }), 201


@bp.route("/api/existing", methods=["GET"])
@login_required
def list_existing():
    """Scan /etc/dnsmasq.conf and /etc/dnsmasq.d/*.conf (excluding server-gui.conf)
    for DHCP directives so users can see what's already configured outside GUI control.
    """
    sources: list[dict] = []
    ranges: list[dict] = []
    static_hosts: list[dict] = []
    options: list[dict] = []

    for p in _dnsmasq_config_files():
        try:
            text = p.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        sources.append({"path": str(p), "name": p.name})
        for line in text.splitlines():
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                continue
            if stripped.startswith("dhcp-range="):
                ranges.append({"source": p.name, "raw": stripped[len("dhcp-range="):]})
            elif stripped.startswith("dhcp-host="):
                static_hosts.append({"source": p.name, "raw": stripped[len("dhcp-host="):]})
            elif stripped.startswith("dhcp-option="):
                options.append({"source": p.name, "raw": stripped[len("dhcp-option="):]})

    return jsonify({
        "sources": sources,
        "ranges": ranges,
        "static_hosts": static_hosts,
        "options": options,
    })


@bp.route("/api/leases", methods=["GET"])
@login_required
def list_leases():
    """Read dnsmasq lease files across distro-specific default locations."""
    leases: list[dict] = []
    errors: list[str] = []
    checked: list[str] = []
    seen: set[tuple[str, str, str, str]] = set()
    sources: set[str] = set()

    for lease_file in _lease_file_candidates():
        checked.append(str(lease_file))
        if not lease_file.exists():
            continue
        try:
            text = lease_file.read_text(encoding="utf-8", errors="replace")
        except OSError as e:
            errors.append(f"{lease_file}: {e}")
            continue
        for lease in _parse_lease_text(text, lease_file):
            key = (lease["expires"], lease["mac"], lease["ip"], lease["client_id"])
            if key in seen:
                continue
            seen.add(key)
            sources.add(str(lease_file))
            leases.append(lease)

    if leases:
        return jsonify({"leases": leases, "sources": sorted(sources), "checked": checked})

    response = {
        "leases": [],
        "checked": checked,
        "note": "lease file not found or empty (DHCP may be inactive)",
    }
    if errors:
        response["error"] = "; ".join(errors)
    return jsonify(response)


@bp.route("/api/leases/release", methods=["POST"])
@login_required
@csrf_protect
def release_leases():
    """Release selected or all active dnsmasq leases by editing the lease DB safely."""
    payload = request.get_json(force=True, silent=True) or {}
    release_all = payload.get("all") is True
    allowed_sources = {str(path) for path in _lease_file_candidates()}
    targets = []

    if not release_all:
        raw_targets = payload.get("leases") or []
        if not isinstance(raw_targets, list) or not raw_targets:
            return jsonify({"error": "解放対象のリースを選択してください"}), 400
        for item in raw_targets:
            if not isinstance(item, dict):
                return jsonify({"error": "リース指定が不正です"}), 400
            source = str(item.get("source", "")).strip()
            if source not in allowed_sources:
                return jsonify({"error": f"許可されていないリースファイルです: {source}"}), 400
            try:
                mac = validate_mac(str(item.get("mac", "")).strip())
                ip = validate_ipv4(str(item.get("ip", "")).strip())
            except ValidationError as e:
                return jsonify({"error": str(e)}), 400
            client_id = str(item.get("client_id", "")).strip()
            if "\n" in client_id or len(client_id) > 256:
                return jsonify({"error": "client-id が不正です"}), 400
            targets.append({"source": source, "mac": mac, "ip": ip, "client_id": client_id})

    lease_files = [str(path) for path in _lease_file_candidates() if path.exists()]
    if not lease_files:
        return jsonify({
            "ok": True,
            "released_count": 0,
            "released": [],
            "note": "リースファイルが見つかりません",
        })

    # リース削除は root 権限と dnsmasq の短時間停止が必要なため、限定した Python 処理を sudo で実行する。
    result = sudo_run(
        ["python3", "-c", _LEASE_RELEASE_SCRIPT],
        stdin=json.dumps({"paths": lease_files, "all": release_all, "targets": targets}, ensure_ascii=False),
        timeout=90,
    )
    try:
        data = json.loads(result.stdout.strip() or "{}")
    except json.JSONDecodeError:
        data = {}
    if not result.ok or not data.get("ok"):
        error = data.get("error") or result.stderr.strip() or result.stdout.strip() or "lease release failed"
        return jsonify({"error": error, "stdout": result.stdout, "stderr": result.stderr}), 500
    return jsonify(data)


def _parse_lease_text(text: str, lease_file: Path) -> list[dict]:
    """Parse dnsmasq's whitespace-separated lease format."""
    leases: list[dict] = []
    for line in text.splitlines():
        parts = line.strip().split()
        if len(parts) < 5:
            continue
        leases.append({
            "expires": parts[0],
            "mac": parts[1],
            "ip": parts[2],
            "hostname": parts[3] if parts[3] != "*" else "",
            "client_id": parts[4],
            "source": str(lease_file),
        })
    return leases


def _lease_file_candidates() -> list[Path]:
    """Return configured and known dnsmasq lease-file paths without duplicates."""
    candidates: list[Path] = []
    seen: set[str] = set()

    def add(path: Path) -> None:
        key = str(path)
        if key not in seen:
            seen.add(key)
            candidates.append(path)

    for path in _configured_lease_files():
        add(path)
    for path in LEASE_FILE_CANDIDATES:
        add(path)
    for directory in LEASE_GLOB_DIRS:
        try:
            for path in sorted(directory.glob("*.leases")):
                add(path)
        except OSError:
            continue
    return candidates


def _configured_lease_files() -> list[Path]:
    """Find explicit dhcp-leasefile directives in the effective dnsmasq config set."""
    paths: list[Path] = []
    for config_file in _dnsmasq_config_files(include_generated=True):
        try:
            text = config_file.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for line in text.splitlines():
            stripped = line.split("#", 1)[0].strip()
            if not stripped.startswith("dhcp-leasefile="):
                continue
            value = stripped.partition("=")[2].strip().strip("\"'")
            if value:
                paths.append(Path(value))
    return paths


def _dnsmasq_config_files(include_generated: bool = False) -> list[Path]:
    """List dnsmasq config files in scan order."""
    candidates: list[Path] = []
    if DNSMASQ_CONF.exists():
        candidates.append(DNSMASQ_CONF)
    if DNSMASQ_D.exists():
        for p in sorted(DNSMASQ_D.glob("*.conf")):
            if not include_generated and p.name == OUR_FILE_NAME:
                continue
            candidates.append(p)
    return candidates


